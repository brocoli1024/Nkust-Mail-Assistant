const assert=require('node:assert/strict');
const p=require('../app/static/web/office-mail-preferences.js');
const value={version:1,campuses:['jiangong','nanzih'],skipped:false};
assert.deepEqual(p.parsePreference(JSON.stringify(value)),value);
assert.throws(()=>p.parsePreference('{broken'));
assert.throws(()=>p.parsePreference(JSON.stringify({version:1,campuses:['private'],skipped:false})));
assert.throws(()=>p.parsePreference(JSON.stringify({...value,email:'PRIVATE'})));
const memory=new Map();const storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
assert.equal(p.writePreference(storage,value).error,false);assert.deepEqual(p.readPreference(storage).value,value);
const blocked={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')},removeItem(){throw Error('blocked')}};
assert.equal(p.readPreference(blocked).error,true);assert.equal(p.writePreference(blocked,value).error,true);
const url=p.urlFor('/public/office-mail?q=test&category=活動&page=5',value,'priority');
const query=new URL(url,'https://local.invalid').searchParams;
assert.equal(query.get('q'),'test');assert.equal(query.get('category'),'活動');assert.equal(query.get('page'),'1');assert.deepEqual(query.getAll('campus'),value.campuses);
assert.equal(p.restoreUrl('/public/office-mail?mode=all',value),null);
assert.equal(p.restoreUrl('/public/office-mail?campus=qijin',value),null);
assert.ok(p.restoreUrl('/public/office-mail',value).includes('mode=priority'));
assert.equal(p.restoreUrl('/public/office-mail',{version:1,campuses:[],skipped:true}),null);
assert.throws(()=>p.urlFor('https://evil.invalid/',value,'priority'));
assert.equal(p.clearPreference(storage).error,false);assert.equal(p.readPreference(storage).value,null);
console.log('Office campus preference, URL precedence, storage failure and recovery passed');
