const assert=require('node:assert/strict');
const {createUpdater,restoreSearchValues}=require('../app/static/web/office-mail-preferences.js');
(async()=>{
 const pending=[],commits=[],histories=[],reports=[];
 const update=createUpdater({load:(url,signal)=>new Promise((resolve,reject)=>pending.push({url,signal,resolve,reject})),commit:x=>commits.push(x),history:(...x)=>histories.push(x),report:(...x)=>reports.push(x)});
 const one=update('/first');const two=update('/second');
 assert.equal(pending[0].signal.aborted,true);
 pending[1].resolve('second');await two;pending[0].resolve('first');await one;
 assert.deepEqual(commits,['second']);assert.deepEqual(histories,[['/second','push']]);
 const failed=update('/failed');pending[2].reject(Error('offline'));await failed;
 assert.deepEqual(commits,['second']);assert.equal(histories.length,1);assert.equal(reports.at(-1)[0],'error');
 const retry=update('/failed');pending[3].resolve('retried');await retry;
 assert.deepEqual(commits,['second','retried']);
 const back=update('/back','none');pending[4].resolve('back');await back;
 assert.equal(histories.length,2);assert.equal(commits.at(-1),'back');
 const restore=update('/restore','replace');pending[5].resolve('restore');await restore;
 assert.deepEqual(histories.at(-1),['/restore','replace']);
 const fields={q:{value:'B'},category:{value:'活動'}};
 const received={q:{value:'A'},category:{value:'課程'}};
 const fake=values=>({querySelector:selector=>values[selector.match(/name="(.*?)"/)[1]]});
 restoreSearchValues(fake(fields),fake(received));
 assert.equal(fields.q.value,'A');assert.equal(fields.category.value,'課程');
 const fallback=[],failureModes=[];
 const historyUpdate=createUpdater({load:async url=>{if(url==='/A')throw Error('offline');return url;},commit:()=>{},history:(...x)=>fallback.push(x),report:(state,mode)=>failureModes.push([state,mode])});
 await historyUpdate('/B');await historyUpdate('/A','none');
 assert.deepEqual(fallback.at(-1),['/B','replace']);
 assert.deepEqual(failureModes.at(-1),['error','replace']);
 console.log('Office partial update: stale requests, failure retention, retry, back and restore passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
